import java.util.Properties
import org.gradle.api.Project

fun loadGoogleMapsAndroidKey(root: Project): String {
    System.getenv("GOOGLE_MAPS_ANDROID_KEY")?.trim()?.takeIf { it.isNotEmpty() }?.let { return it }
    val f = root.file("local.properties")
    if (!f.exists()) return ""
    return Properties()
        .apply { f.inputStream().use { load(it) } }
        .getProperty("GOOGLE_MAPS_ANDROID_KEY")
        ?.trim()
        .orEmpty()
}

